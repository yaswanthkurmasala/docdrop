import { NextResponse } from "next/server";

const decodeKey = (encoded: string): string => {
  try {
    return Buffer.from(encoded, "base64").toString("utf-8");
  } catch {
    return "";
  }
};

const DEFAULT_GEMINI_KEY = decodeKey("QVEuQWI4Uk42SXBvTUF4NGllckU3REM5ajZwaVU0YmUtVXlNZEd6S0oyOGVOTXBST0JtT0E=");

const GEMINI_API_KEY =
  process.env.GEMINI_API_KEY ||
  process.env.NEXT_PUBLIC_GEMINI_API_KEY ||
  DEFAULT_GEMINI_KEY;

const GEMINI_ENDPOINT =
  "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent";

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const { task, text, targetLanguage, imageBase64, mimeType, prompt, question } = body;

    const apiKey = body.apiKey || GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { error: "Gemini API key is not configured" },
        { status: 400 }
      );
    }

    const url = `${GEMINI_ENDPOINT}?key=${apiKey}`;

    let contents: any[] = [];

    if (task === "summarize") {
      const systemPrompt = `You are a world-class executive document analyst. Analyze the following document text and provide an executive-level summary in GitHub-Flavored Markdown.

Format the response cleanly with the following sections:
# Executive Document Summary

## 📌 High-Level Synthesis
(A concise, executive summary of the document's core thesis or purpose, 2-3 paragraphs)

## 🎯 Key Strategic Takeaways
(5-7 bullet points of high-priority findings, metrics, and core decisions)

## ⚠️ Risks, Obligations & Critical Deadlines
(Bullet points highlighting any legal, financial, or operational liabilities, risks, conditions, or dates mentioned)

## 🚀 Recommended Action Items
(Clear, actionable next steps for stakeholders)

---
Document text to analyze:
${(text || "").slice(0, 80000)}
`;

      contents = [{ parts: [{ text: systemPrompt }] }];
    } else if (task === "translate") {
      const systemPrompt = `You are a professional multilingual translator specializing in technical, legal, and business documentation.
Translate the following document content into ${targetLanguage || "Spanish"}.
Maintain all structural markdown, tables, bullet points, headers, and numeric values exactly.

Original content:
${(text || "").slice(0, 60000)}
`;

      contents = [{ parts: [{ text: systemPrompt }] }];
    } else if (task === "ocr") {
      if (!imageBase64) {
        return NextResponse.json({ error: "No imageBase64 provided for OCR" }, { status: 400 });
      }

      const cleanBase64 = imageBase64.replace(/^data:image\/[a-z]+;base64,/, "");

      contents = [
        {
          parts: [
            {
              text: "Perform high-accuracy Optical Character Recognition (OCR) on this scanned document page. Extract all printed text, handwritten notes, labels, numbers, and tabular data. Format any detected tables into clean GitHub-Flavored Markdown tables (| Col 1 | Col 2 |). Preserve original headings and paragraph structure. Return only the extracted markdown text.",
            },
            {
              inlineData: {
                mimeType: mimeType || "image/jpeg",
                data: cleanBase64,
              },
            },
          ],
        },
      ];
    } else if (task === "enhance-markdown") {
      contents = [
        {
          parts: [
            {
              text: `Clean up, structure, and format the following raw text extracted from a PDF into pristine, publication-grade GitHub-Flavored Markdown. Convert any tables or lists into proper markdown formatting. Do not hallucinate or omit content.\n\nContent:\n${(text || "").slice(0, 60000)}`,
            },
          ],
        },
      ];
    } else if (task === "chat" || task === "ask") {
      contents = [
        {
          parts: [
            {
              text: `You are an AI document assistant. Answer the user's question based strictly on the provided document text. If the answer cannot be found in the document, state that clearly.\n\nDocument Context:\n${(text || "").slice(0, 60000)}\n\nUser Question: ${question || prompt}`,
            },
          ],
        },
      ];
    } else {
      // General prompt fallback
      contents = [{ parts: [{ text: prompt || text || "Hello Gemini" }] }];
    }

    const geminiRes = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ contents }),
    });

    const geminiData = await geminiRes.json();

    if (!geminiRes.ok) {
      const errorMsg = geminiData.error?.message || `Gemini API returned status ${geminiRes.status}`;
      return NextResponse.json({ error: errorMsg }, { status: geminiRes.status });
    }

    const outputText =
      geminiData.candidates?.[0]?.content?.parts?.[0]?.text || "No response generated by Gemini.";

    return NextResponse.json({
      success: true,
      text: outputText,
      model: "gemini-2.5-flash",
    });
  } catch (err: any) {
    return NextResponse.json(
      { error: err.message || "Failed to call Gemini AI" },
      { status: 500 }
    );
  }
}
